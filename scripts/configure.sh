#!/bin/sh
# ffmpeg-rt :: configure FFmpeg 9.0.2 as shared DLLs, for one target and variant.
#
#   arm32 use     PGO (pgo/ffshared-arm32.profdata) + ThinLTO. The release build.
#   arm32 plain   the same without the profile and LTO.
#   arm32 instr   -fprofile-generate: the counting build for a new training run (pgo/README.md).
#   x86   plain   desktop Windows x86, nasm SIMD. (The profile is ARM code: no x86 PGO.)
#
# Build folder build/<arch>-<variant>; build.sh installs into dist/<arch>-<variant>.
# Run from an MSYS2 shell, after fetch-deps.sh, gen-rsp.sh and build-deps.sh <arch>.
# Then: gate-config.sh, build.sh, verify-build.sh -- all with the same <arch> <variant>.
#
# Usage: sh scripts/configure.sh <arm32|x86> <use|plain|instr>
set -u
FF_SELF=$0
FF_ROOT=$(cd "$(dirname "$0")/.." && pwd)
. "$FF_ROOT/config.sh"
rt_check_config || exit 1
ARCH=${1:-}; VARIANT=${2:-}
case "$ARCH-$VARIANT" in
  arm32-use|arm32-plain|arm32-instr|x86-plain) ;;
  *) echo "usage: sh scripts/configure.sh <arm32 use|arm32 plain|arm32 instr|x86 plain>"; exit 1 ;;
esac
w() { cygpath -m "$1" 2>/dev/null || echo "$1"; }
u() { cygpath -u "$1" 2>/dev/null || echo "$1"; }

X=$FF_ROOT/cross
SRC=$(u "$DEPS")/ffmpeg-$FFMPEG_VER
B=$(u "$BUILD")/$ARCH-$VARIANT
PFX=$(w "$BUILD/prefix-$ARCH")
RT=$(w "$RT2")
[ -f "$SRC/.ffmpeg-rt-patched" ] || { echo "no patched FFmpeg at $SRC: run sh scripts/fetch-deps.sh"; exit 1; }
[ -f "$(u "$PFX")/lib/libdav1d.lib" ] && [ -f "$(u "$PFX")/lib/z.lib" ] \
  || { echo "no zlib/dav1d in $PFX: run sh scripts/build-deps.sh $ARCH"; exit 1; }
[ -f "$X/$ARCH-msvc.rsp" ] && [ -f "$X/$ARCH-link.rsp" ] || { echo "no cross/$ARCH-*.rsp: run sh scripts/gen-rsp.sh"; exit 1; }

# ---- the C compiler for this build: build/<arch>-<variant>/cc.sh -------------------------------
# The PGO name of a static function is "<source file path>;<function>". The profile in pgo/
# stores it with the source folder cut off ("libavcodec/h264_cabac.c;decode_cabac_residual_..."),
# and -static-func-strip-dirname-prefix=N cuts this checkout's own source folder off, N being
# its depth in the path clang sees (F:/a/b/deps/ffmpeg-9.0.2/ -> 5). So the profile fits
# wherever the clone is, and a training run here makes a profile that fits anywhere too.
# Measured: on h264_cabac.c and h264_mb.c this gives code identical to a build at the original
# path with the original full-path profile.
STRIP=$(printf '%s/' "$(w "$SRC")" | tr -cd '/' | wc -c | tr -d ' ')
EXTRA=""; LIBPATH=""
case "$VARIANT" in
  use)
    PROF=$FF_ROOT/pgo/ffshared-arm32.profdata
    [ -f "$PROF" ] || { echo "no $PROF"; exit 1; }
    # -pgso=false: no profile-guided size optimisation of cold code in the compile step. The
    # ThinLTO link runs with lld's defaults, as the release build did.
    EXTRA="-fprofile-use=$(w "$PROF") -flto=thin -mllvm -pgso=false -mllvm -static-func-strip-dirname-prefix=$STRIP -Wno-profile-instr-unprofiled -Wno-profile-instr-out-of-date -Wno-backend-plugin" ;;
  instr)
    EXTRA="-fprofile-generate -mllvm -static-func-strip-dirname-prefix=$STRIP"
    # the profile runtime (clang_rt.profile-arm.lib) lives in the toolchain's own lib folder
    PRT=$(ls "$(u "$RT2")"/../lib/clang/*/lib/windows/clang_rt.profile-arm.lib 2>/dev/null | head -1)
    [ -n "$PRT" ] || { echo "no clang_rt.profile-arm.lib under $RT2/../lib/clang"; exit 1; }
    LIBPATH="-libpath:$(w "$(dirname "$PRT")")" ;;
esac
rm -rf "$B"; mkdir -p "$B" || exit 1
cat > "$B/cc.sh" <<EOF
#!/bin/sh
# Generated by scripts/configure.sh $ARCH $VARIANT: the C compiler of this build (--cc and --cxx).
# clang-cl, MSVC ABI, static CRT (-MT). The @rsp carries -vctoolsdir etc: their values contain a
# space and cannot survive configure's word splitting as bare flags. Never pass the rsp through
# --extra-cflags: configure feeds those to the assembler too (configure:5509).
exec "$RT/clang-cl.exe" "@$FF_ROOT_W/cross/$ARCH-msvc.rsp" -MT $EXTRA "\$@"
EOF
chmod +x "$B/cc.sh"

case "$ARCH" in
  arm32) TARGET="--arch=arm --as=$X/as-arm32.sh --windres=$X/windres-arm32.sh --enable-asm --enable-neon --enable-thumb" ;;
  x86)   [ -f "$(u "$NASM")" ] || { echo "no nasm at $NASM: run sh scripts/build-nasm.sh"; exit 1; }
         TARGET="--arch=x86 --cpu=i686 --windres=$X/windres-x86.sh --x86asmexe=$(w "$NASM")" ;;
esac

export PATH="$FF_ROOT/cross/bin:/usr/bin:/usr/local/bin:$PATH"   # cross/bin/lib.exe: FFmpeg's makedef wants lib.exe
cd "$B" || exit 1
export TMPDIR=.
export TMP="${TMP:-$MSYS2/tmp}" TEMP="${TEMP:-$MSYS2/tmp}"
export NM="$RT/llvm-nm.exe"

# The components: TelegArm's list (decoders, all demuxers/parsers/bsfs, non-network protocols,
# mp4/matroska muxers, avfilter with atempo/aformat/aresample) plus libdav1d (software AV1:
# FFmpeg's own av1 decoder needs a hardware accelerator), zlib, and ffmpeg.exe with the null
# output (the device kits' workload, and a test tool). LGPL: neither the GPL nor the nonfree switch
# is on this line (THIRD-PARTY-NOTICES.md), and gate-config.sh checks config.h for both.
"$SRC/configure" \
  --prefix="$(u "$DIST")/$ARCH-$VARIANT" \
  --enable-cross-compile --target-os=win32 $TARGET \
  --cc="$B/cc.sh" --cxx="$B/cc.sh" \
  --ld="$RT/lld-link.exe" --ar="$RT/llvm-lib.exe" --nm="$RT/llvm-nm.exe" \
  --ranlib="$RT/llvm-ranlib.exe" --strip="$RT/llvm-strip.exe" \
  --host-cc="$X/hostcc-x64.sh" --host-ld="$RT/lld-link.exe" --host-ldflags="@$FF_ROOT_W/cross/x64-link.rsp" \
  --enable-shared --disable-static --enable-w32threads \
  --disable-everything --disable-doc --disable-avdevice --disable-network --disable-autodetect \
  --disable-programs --enable-ffmpeg --enable-zlib --enable-libdav1d --enable-dxva2 --enable-hwaccel=h264_dxva2 \
  --enable-decoder=libdav1d,h264,hevc,av1,vp8,vp9,opus,aac,flac,mp3,mp3float,vorbis,mpeg4,h263,alac \
  --enable-decoder=pcm_s16le,pcm_s16be,pcm_s24le,pcm_s24be,pcm_s32le,pcm_f32le,pcm_f64le,pcm_u8,pcm_alaw,pcm_mulaw \
  --enable-demuxers --enable-parsers --enable-bsfs --enable-protocols \
  --enable-muxer=mp4,matroska,null --enable-encoder=wrapped_avframe,pcm_s16le \
  --enable-avfilter --enable-filter=atempo,aformat,aresample,format,scale,null,anull \
  --enable-swscale --enable-swresample --extra-version=kodi-rt \
  --extra-cflags="-I$PFX/include -DWIN32_LEAN_AND_MEAN" \
  --extra-ldflags="@$FF_ROOT_W/cross/$ARCH-link.rsp -libpath:$PFX/lib $LIBPATH"
rc=$?
echo "===CONFIGURE EXIT=$rc==="
[ $rc -eq 0 ] || { tail -40 ffbuild/config.log; echo "CONFIGURE FAILED"; exit 1; }
echo "next: sh scripts/gate-config.sh $ARCH $VARIANT"
